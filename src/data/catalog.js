const STOCK_LABEL = {
  in: 'In Stock',
  low: 'Low Stock',
  out: 'Out of Stock',
}

function item(data) {
  const originalPrice = data.originalPrice ?? null
  const discount =
    data.discount ??
    (originalPrice ? Math.round((1 - data.price / originalPrice) * 100) : 0)
  const stock = data.stock ?? 'in'
  return {
    featured: false,
    popular: 50,
    keywords: [],
    model: null,
    modelColor: '#c45d2c',
    createdAt: '2026-06-15',
    description: '',
    note: '',
    ...data,
    originalPrice,
    discount,
    stock,
    stockLabel: STOCK_LABEL[stock],
  }
}

